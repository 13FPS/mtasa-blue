    template <std::size_t N, std::size_t M>
    constexpr bool HasExactSubspan(const std::array<unsigned char, N>& whole, std::size_t offset, const std::array<unsigned char, M>& part) noexcept
    {
        if (offset > N || M > N - offset)
            return false;
        for (std::size_t index = 0; index < M; ++index)
            if (whole[offset + index] != part[index])
                return false;
        return true;
    }

